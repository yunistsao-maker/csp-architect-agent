"""Generate the icon catalogs used by the Azure and GCP diagram skills from drawio_icons.json.

Run after scripts/dump_drawio_icons.py so skills, prompts and the validator share one source of truth:
    python scripts/build_icon_catalogs.py
"""
import json
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ICONS = json.loads((ROOT / "drawio_icons.json").read_text())
HEADER = "<!-- Generated by scripts/build_icon_catalogs.py from drawio_icons.json. Do not edit by hand. -->\n"

# Azure: one file per draw.io category so the model only reads what it needs.
AZ_DIR = ROOT / "skills/azure-architecture-diagram/references/icons"
AZ_DIR.mkdir(parents=True, exist_ok=True)
by_cat = defaultdict(list)
for path in ICONS["azure2"]:
    cat, name = path.split("/", 1)
    by_cat[cat].append(path)
for old in AZ_DIR.glob("*.md"):
    old.unlink()
index = []
for cat, paths in sorted(by_cat.items()):
    lines = [HEADER, f"# Azure icons: {cat} ({len(paths)})", "",
             "Style: `image;aspect=fixed;html=1;align=center;fontSize=12;image=img/lib/azure2/<path>;`", ""]
    lines += [f"- {p}" for p in sorted(paths)]
    (AZ_DIR / f"{cat}.md").write_text("\n".join(lines) + "\n")
    index.append(f"- `references/icons/{cat}.md` ({len(paths)})")
(AZ_DIR.parent / "icon-index.md").write_text(
    HEADER + "# Azure icon catalog index\n\nRead only the categories you need:\n\n" + "\n".join(index) + "\n")

# GCP: GCP2 hexagon icons (prIcon names) in one file.
gcp = ROOT / "skills/gcp-architecture-diagram/references/gcp2-icons.md"
gcp.parent.mkdir(parents=True, exist_ok=True)
names = sorted(ICONS["gcp2"])
gcp.write_text(HEADER + f"# GCP2 icon names ({len(names)})\n\n"
               "Style: `...;shape=mxgraph.gcp2.hexIcon;prIcon=<name>;`. Includes product icons and generic pictograms (users, external_data_center, folders, ...).\n\n"
               + "\n".join(f"- {n}" for n in names) + "\n")
print(f"azure: {len(by_cat)} category files, {len(ICONS['azure2'])} icons; gcp2: {len(names)} icons")
