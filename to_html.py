"""Bundle one or more .drawio diagrams into a single tabbed HTML page for demos.

Usage: python to_html.py <out.html> <diagram.drawio> [more.drawio ...] [--title "..."]

Each diagram becomes a tab rendered by the draw.io viewer (zoom, pan, fullscreen, edit link).
If a matching <name>.md exists next to a diagram (as written by invoke.py), it is shown below it.
The page loads viewer-static.min.js from viewer.diagrams.net, so it needs internet access to render.
"""

import argparse
import html
import json
from pathlib import Path

import markdown

COLORS = ["#FF9900", "#4285F4", "#0078D4", "#34A853", "#8E44AD", "#E74C3C"]


def build(diagrams: list[Path], title: str) -> str:
    tabs, panes = [], []
    for i, path in enumerate(diagrams):
        key, color = f"d{i}", COLORS[i % len(COLORS)]
        cfg = {"highlight": color, "nav": True, "resize": True, "toolbar": "zoom layers lightbox",
               "edit": "_blank", "xml": path.read_text(encoding="utf-8")}
        md_path = path.with_suffix(".md")
        explanation = markdown.markdown(md_path.read_text(encoding="utf-8"), extensions=["tables"]) if md_path.exists() else ""
        tabs.append(f'<button class="tab" data-t="{key}" style="--c:{color}">{html.escape(path.stem)}</button>')
        panes.append(f'<section id="{key}" class="pane active"><div class="diagram">'
                     f'<div class="mxgraph" style="max-width:100%;border:1px solid #ddd" data-mxgraph="{html.escape(json.dumps(cfg))}"></div>'
                     f'</div><article>{explanation}</article></section>')
    return f"""<!doctype html><html><head><meta charset="utf-8"><title>{html.escape(title)}</title>
<style>
body{{font-family:system-ui,-apple-system,"Segoe UI",sans-serif;margin:0;background:#f6f7f9;color:#1d2330}}
header{{background:#1d2330;color:#fff;padding:18px 32px}} header h1{{margin:0;font-size:22px}} header p{{margin:4px 0 0;opacity:.7;font-size:14px}}
nav{{display:flex;gap:8px;padding:16px 32px 0}}
.tab{{border:0;padding:10px 20px;border-radius:8px 8px 0 0;background:#e3e6eb;cursor:pointer;font-size:15px;font-weight:600;border-top:4px solid transparent}}
.tab.active{{background:#fff;border-top-color:var(--c)}}
.pane{{display:none;background:#fff;margin:0 32px 32px;padding:24px;border-radius:0 8px 8px 8px}} .pane.active{{display:block}}
.diagram{{overflow:auto}} article{{max-width:1000px;margin-top:24px;line-height:1.55}}
article table{{border-collapse:collapse}} article td,article th{{border:1px solid #ddd;padding:6px 10px}} code{{background:#f0f1f3;padding:1px 4px;border-radius:3px}}
</style></head><body>
<header><h1>{html.escape(title)}</h1><p>Generated by CSP Architect Agent (Amazon Bedrock AgentCore) · scroll to zoom · click ⛶ for fullscreen</p></header>
<nav>{"".join(tabs)}</nav>{"".join(panes)}
<script>
document.querySelectorAll('.tab').forEach(b=>b.onclick=()=>{{
  document.querySelectorAll('.tab,.pane').forEach(e=>e.classList.remove('active'));
  b.classList.add('active'); document.getElementById(b.dataset.t).classList.add('active');
  window.dispatchEvent(new Event('resize'));}});
// Render every diagram while visible (hidden ones get zero size), then show only the first tab.
window.addEventListener('load',()=>setTimeout(()=>document.querySelector('.tab').click(),1500));
</script>
<script src="https://viewer.diagrams.net/js/viewer-static.min.js"></script>
</body></html>"""


if __name__ == "__main__":
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("out")
    ap.add_argument("diagrams", nargs="+", type=Path)
    ap.add_argument("--title", default="Architecture Diagrams")
    args = ap.parse_args()
    Path(args.out).write_text(build(args.diagrams, args.title), encoding="utf-8")
    print(f"Saved {args.out} ({len(args.diagrams)} diagram(s))")
